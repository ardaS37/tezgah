export const normalizeLocale = (locale) => locale === 'tr' ? 'tr' : DEFAULT_LOCALE;
export const getLocale = () => selectedLocale;
export function setLocale(locale) { selectedLocale = normalizeLocale(locale); }

export function translate(locale, source, values) {
  const text = normalizeLocale(locale) === 'en' && Object.hasOwn(english, source) ? english[source] : source;
  return values ? text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match) : text;
}

export const t = (source, values) => translate(selectedLocale, source, values);

export function localizePage() {
  document.documentElement.lang = getLocale();
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    const source = `data-i18n-${attribute}`;
    for (const node of document.querySelectorAll(`[${source}]`)) node.setAttribute(attribute, t(node.getAttribute(source)));
  }
}
